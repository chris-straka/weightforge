fn glyph(c: char) -> Option<&'static [&'static str; 7]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|g| g.0 == c).map(|g| &g.1)
}

/// Pixel width of `text` at `scale`.
pub fn text_width(text: &str, scale: usize) -> usize {
    text.chars().count() * 6 * scale
}

/// Draws `text` into an RGB buffer of width `w` with its top-left at (x, y).
pub fn draw_text(buf: &mut [u8], w: usize, h: usize, x: usize, y: usize, text: &str, scale: usize, rgb: [u8; 3]) {
    let mut cx = x;
    for c in text.chars() {
        if let Some(g) = glyph(c) {
            for (row, line) in g.iter().enumerate() {
                for (col, ch) in line.bytes().enumerate() {
                    if ch != b'#' {
                        continue;
                    }
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let px = cx + col * scale + dx;
                            let py = y + row * scale + dy;
                            if px < w && py < h {
                                let o = (py * w + px) * 3;
                                buf[o..o + 3].copy_from_slice(&rgb);
                            }
                        }
                    }
                }
            }
        }
        cx += 6 * scale;
    }
}
